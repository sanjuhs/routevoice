def packed(vals,bits):
    return sum(int(v) << (bits*i) for i,v in enumerate(vals))
def emit(name,rows,external,idx,books):
    s=[f'''// Generated by gen_fabric.py; signed 9-bit x, unsigned 8-bit W.
// Row/book ports are INTERNAL ARRAY interfaces, not package IO.
module {name}(
 input wire clk, input wire rst_n, input wire start,
 input wire signed [8:0] x, input wire x_valid, output wire x_ready,
 output reg busy, output reg done,
 input wire [8:0] rd_addr, output wire signed [26:0] rd_data,
 output reg signed [17:0] asum,
 output reg [8:0] row_addr''']
    if external: s += [', input wire [1279:0] idx_row, input wire [40959:0] book_row']
    s += ['\n);',f"localparam [8:0] LAST_ROW=9'd{rows-1};", '''reg feeding, pipe_valid, pipe_last;
reg signed [16:0] product_q [0:319];
reg signed [26:0] acc [0:319];
wire signed [12:0] p [0:15];
wire signed [12:0] xe = {{4{x[8]}},x};
assign x_ready = busy && feeding;
assign rd_data = rd_addr < 9'd320 ? acc[rd_addr] : 27'sd0;
''']
    for d in range(16):
        terms=[f'(xe <<< {b})' for b in range(4) if (d>>b)&1]
        s += [f"assign p[{d}] = {' + '.join(terms) if terms else '13\'sd0'};"]
    if not external:
        s += ['reg [1279:0] idx_row;','reg [40959:0] book_row;', 'always @* begin',"idx_row = 1280'd0;",'case (row_addr)']
        for k in range(rows): s += [f"9'd{k}: idx_row = 1280'h{packed(idx[k],4):0320x};"]
        s += ['default: ;','endcase','end','always @* begin',"book_row = 40960'd0;",'case (row_addr[8:6])']
        for g in range(rows//64): s += [f"3'd{g}: book_row = 40960'h{packed(books[g].flatten(),8):010240x};"]
        s += ['default: ;','endcase','end']
    s += ['''genvar n;
generate for(n=0;n<320;n=n+1) begin: lane
 wire [3:0] index_value = idx_row[n*4 +: 4];
 wire [127:0] local_book = book_row[n*128 +: 128];
 wire [7:0] coefficient = local_book[index_value*8 +: 8];
 wire signed [12:0] hi = p[coefficient[7:4]];
 wire signed [12:0] lo = p[coefficient[3:0]];
 wire signed [16:0] hi_ext = {{4{hi[12]}},hi};
 wire signed [16:0] lo_ext = {{4{lo[12]}},lo};
 wire signed [16:0] product = (hi_ext <<< 4) + lo_ext;
 always @(posedge clk) begin
   if (!rst_n) begin acc[n] <= 0; product_q[n] <= 0; end
   else if (start && !busy) begin acc[n] <= 0; end
   else begin
     if (x_valid && x_ready) product_q[n] <= product;
     if (pipe_valid) acc[n] <= acc[n] + {{10{product_q[n][16]}},product_q[n]};
   end
 end
end endgenerate
always @(posedge clk) begin
 if (!rst_n) begin
   busy<=0; done<=0; feeding<=0; row_addr<=0; asum<=0;
   pipe_valid<=0; pipe_last<=0;
 end else begin
   done<=0;
   pipe_valid<=0;
   if (start && !busy) begin
     busy<=1; feeding<=1; row_addr<=0; asum<=0; pipe_last<=0;
   end else begin
     if (x_valid && x_ready) begin
       pipe_valid<=1;
       pipe_last<=(row_addr == LAST_ROW);
       asum<=asum + {{9{x[8]}},x};
       if (row_addr == LAST_ROW) feeding<=0;
       else row_addr<=row_addr+1'b1;
     end
     if (pipe_valid && pipe_last) begin done<=1; busy<=0; end
   end
 end
end
endmodule
''']
    (ROOT/'rtl'/f'{name}.sv').write_text('\n'.join(s))
def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--weights',type=Path,default=DEFAULT); a=ap.parse_args()
    raw=a.weights.read_bytes(); assert len(raw)==12*320*320, len(raw)
    w=np.frombuffer(raw[:102400],dtype=np.uint8).reshape(320,320)
    idx=np.zeros_like(w); books=np.empty((5,320,16),dtype=np.uint8)
    for g in range(5):
        for n in range(320):
            b=np.unique(w[g*64:(g+1)*64,n]); assert len(b)==16,(g,n,len(b))
            books[g,n]=b; idx[g*64:(g+1)*64,n]=np.searchsorted(b,w[g*64:(g+1)*64,n])
    reconstructed=np.empty_like(w)
    for k in range(320):
        for n in range(320):
            reconstructed[k,n]=books[k//64,n,idx[k,n]]
            assert reconstructed[k,n]==w[k,n],(k,n)
    np.savez(ROOT/'vectors'/'topology.npz',indices=idx,books=books)
    (ROOT/'vectors'/'weights-image0.bin').write_bytes(raw[:102400])
    (ROOT/'vectors'/'idx.hex').write_text(''.join(f'{packed(r,4):0320x}\n' for r in idx))
    (ROOT/'vectors'/'book.hex').write_text(''.join(f'{packed(r.flatten(),8):010240x}\n' for r in books))
    rng=np.random.default_rng(20261014)
    xs=[np.zeros(320,dtype=np.int64),np.full(320,-256),np.full(320,255),np.tile([-256,255],160)]
    xs.extend(rng.integers(-256,256,size=(20,320),dtype=np.int64))
    for k in [0,63,64,127,128,255,256,319]:
        v=np.zeros(320,dtype=np.int64);v[k]=-256 if k%2 else 255;xs.append(v)
    xs=np.asarray(xs,dtype=np.int64)
    # Independent oracle uses only the original UINT8 bytes, never idx/books.
    for rows in [320,64]:
        ys=xs[:,:rows] @ w[:rows].astype(np.int64)
        sums=xs[:,:rows].sum(axis=1)
        (ROOT/'vectors'/f'x{rows}.hex').write_text(''.join(f'{int(v)&511:03x}\n' for v in xs[:,:rows].flatten()))
        (ROOT/'vectors'/f'y{rows}.hex').write_text(''.join(f'{int(v)&((1<<27)-1):07x}\n' for v in ys.flatten()))
        (ROOT/'vectors'/f'asum{rows}.hex').write_text(''.join(f'{int(v)&((1<<18)-1):05x}\n' for v in sums))
    for name,rows,external in [('rv_fixed_proj320_rom',320,False),('rv_fixed_proj320_dp',320,True),('rv_fixed_proj64x320_rom',64,False)]:
        emit(name,rows,external,idx,books)
    manifest={'source':str(a.weights),'source_sha256':hashlib.sha256(raw).hexdigest(),'image0_sha256':hashlib.sha256(raw[:102400]).hexdigest(),'shape':[320,320],'layout':'W[k,n]=image[k*320+n]','reconstruction_assertions':102400,'books':1600,'book_size':16,'vectors':len(xs),'random_vectors':20,'seed':20261014,'activation_bits':9,'representative_bits':8,'index_bits':4,'partial_product_bits':13,'product_bits':17,'accumulator_bits':27,'asum_bits':18,'pipeline_latency_after_last_input_cycles':1,'start_to_done_unstalled_cycles':321}
    (ROOT/'evidence'/'generation.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print('W2-STATUS: generated full ROM, datapath, and 64x320 ROM; 102400 reconstruction assertions passed')
if __name__=='__main__': main()
